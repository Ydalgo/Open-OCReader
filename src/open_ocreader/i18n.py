def tr(lang: str, key: str, **kwargs) -> str:
    """Devuelve la cadena traducida al idioma de interfaz solicitado (respaldo a 'es')."""
    table = STRINGS.get(lang, STRINGS["es"])
    val = table.get(key, STRINGS["es"].get(key, key))
    if isinstance(val, str) and kwargs:
        return val.format(**kwargs)
    return val


def get_llm_language_name(lang_code: str) -> str:
    """Devuelve el nombre del idioma para indicar al LLM en qué idioma responder."""
    return LLM_LANGUAGE_NAMES.get(lang_code, "español de España")
